# --------------------------------------------------------------------------- #
# Evaluator
# --------------------------------------------------------------------------- #
class Evaluator:
    def __init__(self, rows, cols, get_cell):
        self.rows = rows
        self.cols = cols
        self.get_cell = get_cell  # (col,row) -> internal value

    def eval(self, node):
        tag = node[0]
        if tag == "num":
            return node[1]
        if tag == "str":
            return node[1]
        if tag == "bool":
            return node[1]
        if tag == "nameerr":
            return Error("#NAME?")
        if tag == "err":
            return Error(node[1])
        if tag == "ref":
            col, row = node[1]
            if col < 1 or col > self.cols or row < 1 or row > self.rows:
                return Error("#REF!")
            return self.get_cell((col, row))
        if tag == "range":
            return self.eval_range(node[1], node[2])
        if tag == "unary":
            v = self.eval(node[2])
            return op_unary(node[1], v)
        if tag == "binary":
            op = node[1]
            left = self.eval(node[2])
            if op in ("+", "-", "*", "/", "^"):
                return op_arith(op, left, self.eval(node[3]))
            if op == "&":
                return op_concat(left, self.eval(node[3]))
            return op_compare(op, left, self.eval(node[3]))
        if tag == "func":
            return self.eval_func(node[1], node[2])
        raise ParseError("bad node")

    def eval_range(self, p1, p2):
        c1, r1 = p1
        c2, r2 = p2
        cmin, cmax = min(c1, c2), max(c1, c2)
        rmin, rmax = min(r1, r2), max(r1, r2)
        if cmin < 1 or cmax > self.cols or rmin < 1 or rmax > self.rows:
            return Error("#REF!")
        cells = []
        for r in range(rmin, rmax + 1):
            for c in range(cmin, cmax + 1):
                cells.append(self.get_cell((c, r)))
        return RangeValue(cells)

    def eval_func(self, name, arg_nodes):
        if name not in FUNC_ARITY:
            return Error("#NAME?")
        if not check_arity(name, len(arg_nodes)):
            return Error("#VALUE!")

        if name == "IF":
            cond = self.eval(arg_nodes[0])
            b = coerce_bool(cond)
            if is_error(b):
                return b
            return self.eval(arg_nodes[1] if b else arg_nodes[2])

        if name == "IFERROR":
            v = self.eval(arg_nodes[0])
            if isinstance(v, RangeValue):
                v = Error("#VALUE!")
            if is_error(v):
                fb = self.eval(arg_nodes[1])
                if isinstance(fb, RangeValue):
                    return Error("#VALUE!")
                return fb
            return v

        # Eager functions: evaluate all args left-to-right, then propagate the
        # first error found (scalar or inside a range, row-major).
        vals = [self.eval(a) for a in arg_nodes]
        err = first_arg_error(vals)
        if err is not None:
            return err
        return EAGER_FUNCS[name](vals)


# --------------------------------------------------------------------------- #
# Iterative Tarjan SCC (deps-first output order)
# --------------------------------------------------------------------------- #
def tarjan_scc(nodes, succ):
    index = {}
    low = {}
    on_stack = set()
    stack = []
    counter = [0]
    result = []

    for start in nodes:
        if start in index:
            continue
        work = [(start, 0)]
        while work:
            node, pi = work[-1]
            if pi == 0:
                index[node] = counter[0]
                low[node] = counter[0]
                counter[0] += 1
                stack.append(node)
                on_stack.add(node)
            recurse = False
            succs = succ.get(node, ())
            i = pi
            while i < len(succs):
                w = succs[i]
                if w not in index:
                    work[-1] = (node, i + 1)
                    work.append((w, 0))
                    recurse = True
                    break
                elif w in on_stack:
                    if index[w] < low[node]:
                        low[node] = index[w]
                i += 1
            if recurse:
                continue
            if low[node] == index[node]:
                comp = []
                while True:
                    w = stack.pop()
                    on_stack.discard(w)
                    comp.append(w)
                    if w == node:
                        break
                result.append(comp)
            work.pop()
            if work:
                parent = work[-1][0]
                if low[node] < low[parent]:
                    low[parent] = low[node]
    return result


# --------------------------------------------------------------------------- #
# Top-level compute
# --------------------------------------------------------------------------- #
def _canon_literal(raw):
    """Internal value for a non-formula input cell."""
    if raw is None:
        return BLANK
    if isinstance(raw, bool):
        return raw
    if isinstance(raw, (int, float)):
        return raw
    if isinstance(raw, str):
        return raw
    return Error("#VALUE!")


def _to_json(v):
    """Canonicalize an internal value to JSON output form."""
    if is_error(v):
        return v.code
    if isinstance(v, bool):
        return v
    if v is BLANK:
        return None
    if isinstance(v, RangeValue):
        return "#VALUE!"
    if isinstance(v, float):
        if v.is_integer():
            return int(v)
        return v
    return v


def compute(data):
    rows = data.get("rows")
    cols = data.get("cols")
    cells = data.get("cells", {})
    if not isinstance(rows, int) or not isinstance(cols, int):
        raise ValueError("rows and cols are required integers")

    # Classify cells.
    key_by_coord = {}          # (col,row) -> original key string
    original_keys = list(cells.keys())
    literal_values = {}        # (col,row) -> internal value
    formula_ast = {}           # (col,row) -> AST (or ('err', token))
    coord_of_key = {}          # original key -> (col,row)

    for key in original_keys:
        coord = parse_addr(key)
        coord_of_key[key] = coord
        key_by_coord[coord] = key
        raw = cells[key]
        if isinstance(raw, str) and raw.startswith("="):
            try:
                formula_ast[coord] = parse_formula(raw[1:])
            except (ParseError, ValueError):
                formula_ast[coord] = ("err", "#ERROR!")
        else:
            literal_values[coord] = _canon_literal(raw)

    formula_coords = set(formula_ast.keys())

    # Build dependency graph among formula cells (edges: cell -> formula deps).
    succ = {}
    for coord, ast in formula_ast.items():
        succ[coord] = _formula_deps(ast, formula_coords, cols, rows)

    order = tarjan_scc(list(formula_coords), succ)

    formula_values = {}

    def get_cell(coord):
        if coord in formula_values:
            return formula_values[coord]
        if coord in literal_values:
            return literal_values[coord]
        return BLANK  # in-bounds empty cell

    ev = Evaluator(rows, cols, get_cell)

    for comp in order:
        is_cycle = len(comp) > 1 or (comp[0] in succ.get(comp[0], ()))
        if is_cycle:
            for c in comp:
                formula_values[c] = Error("#CIRCULAR!")
            continue
        coord = comp[0]
        try:
            v = ev.eval(formula_ast[coord])
        except RecursionError:
            v = Error("#ERROR!")
        if isinstance(v, RangeValue):
            v = Error("#VALUE!")
        elif v is BLANK:
            v = 0
        formula_values[coord] = v

    # Assemble output using the ORIGINAL key set.
    out = {}
    for key in original_keys:
        coord = coord_of_key[key]
        if coord in formula_values:
            out[key] = _to_json(formula_values[coord])
        else:
            out[key] = _to_json(literal_values[coord])
    return out


def _formula_deps(ast, formula_coords, cols, rows):
    """Structural dependency edges: which *formula* cells this AST references."""
    deps = []
    seen = set()

    def add(coord):
        if coord in formula_coords and coord not in seen:
            seen.add(coord)
            deps.append(coord)

    def walk(node):
        tag = node[0]
        if tag == "ref":
            add(node[1])
        elif tag == "range":
            (c1, r1), (c2, r2) = node[1], node[2]
            cmin, cmax = min(c1, c2), max(c1, c2)
            rmin, rmax = min(r1, r2), max(r1, r2)
            if cmin < 1 or cmax > cols or rmin < 1 or rmax > rows:
                return
            for r in range(rmin, rmax + 1):
                for c in range(cmin, cmax + 1):
                    add((c, r))
        elif tag == "unary":
            walk(node[2])
        elif tag == "binary":
            walk(node[2])
            walk(node[3])
        elif tag == "func":
            for a in node[2]:
                walk(a)

    walk(ast)
    return deps


def main():
    raw = sys.stdin.buffer.read().decode("utf-8")
    data = json.loads(raw)
    result = compute(data)
    out = json.dumps(result, ensure_ascii=False, separators=(",", ":"),
                     allow_nan=False, sort_keys=True)
    sys.stdout.buffer.write(out.encode("utf-8"))
    sys.stdout.buffer.write(b"\n")


if __name__ == "__main__":
    main()
