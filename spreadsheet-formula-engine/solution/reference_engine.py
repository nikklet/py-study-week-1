# Arity spec: exact int, or (min, None) for variadic-min.
FUNC_ARITY = {
    "SUM": (1, None), "AVERAGE": (1, None), "MIN": (1, None), "MAX": (1, None),
    "COUNT": (1, None), "COUNTA": (1, None), "CONCAT": (1, None),
    "AND": (1, None), "OR": (1, None),
    "IF": 3, "IFERROR": 2, "NOT": 1,
    "ROUND": 2, "MOD": 2, "POWER": 2, "LEFT": 2, "RIGHT": 2, "MID": 3,
    "ABS": 1, "INT": 1, "SQRT": 1, "LEN": 1,
    "UPPER": 1, "LOWER": 1, "TRIM": 1,
}


def check_arity(name, argc):
    spec = FUNC_ARITY[name]
    if isinstance(spec, tuple):
        lo, hi = spec
        if argc < lo:
            return False
        if hi is not None and argc > hi:
            return False
        return True
    return argc == spec


def first_arg_error(vals):
    """Return the first error appearing in args (scalars or inside ranges),
    scanning left-to-right and row-major. This drives error precedence."""
    for v in vals:
        if is_error(v):
            return v
        if isinstance(v, RangeValue):
            for c in v.cells:
                if is_error(c):
                    return c
    return None


def fn_sum(vals):
    total = 0
    for v in vals:
        if isinstance(v, RangeValue):
            for c in v.cells:
                if isinstance(c, bool):
                    continue
                if isinstance(c, (int, float)):
                    total += c
        else:
            n = coerce_number(v)
            if is_error(n):
                return n
            total += n
    return total


def _collect_numbers(vals):
    """Numbers considered by numeric aggregations. Range: numeric cells only.
    Scalar: coerced (bool->1/0, blank->0, text->#VALUE!)."""
    nums = []
    for v in vals:
        if isinstance(v, RangeValue):
            for c in v.cells:
                if isinstance(c, bool):
                    continue
                if isinstance(c, (int, float)):
                    nums.append(c)
        else:
            n = coerce_number(v)
            if is_error(n):
                return None, n
            nums.append(n)
    return nums, None


def fn_average(vals):
    nums, err = _collect_numbers(vals)
    if err is not None:
        return err
    if not nums:
        return Error("#DIV/0!")
    return sum(nums) / len(nums)


def fn_min(vals):
    nums, err = _collect_numbers(vals)
    if err is not None:
        return err
    return min(nums) if nums else 0


def fn_max(vals):
    nums, err = _collect_numbers(vals)
    if err is not None:
        return err
    return max(nums) if nums else 0


def fn_count(vals):
    count = 0
    for v in vals:
        if isinstance(v, RangeValue):
            for c in v.cells:
                if isinstance(c, bool):
                    continue
                if isinstance(c, (int, float)):
                    count += 1
        else:
            if isinstance(v, bool) or isinstance(v, (int, float)):
                count += 1
            elif v is BLANK:
                pass
            else:  # text scalar
                return Error("#VALUE!")
    return count


def fn_counta(vals):
    count = 0
    for v in vals:
        if isinstance(v, RangeValue):
            for c in v.cells:
                if c is not BLANK:
                    count += 1
        else:
            if v is not BLANK:
                count += 1
    return count


def fn_concat(vals):
    parts = []
    for v in vals:
        if isinstance(v, RangeValue):
            for c in v.cells:
                if c is BLANK:
                    continue
                t = coerce_text(c)
                if is_error(t):
                    return t
                parts.append(t)
        else:
            t = coerce_text(v)
            if is_error(t):
                return t
            parts.append(t)
    return "".join(parts)


def _bool_values(vals):
    """Boolean values for AND/OR. Scalar: coerce_bool (blank->FALSE, text->err).
    Range: numeric/bool cells only (blank/text ignored)."""
    out = []
    for v in vals:
        if isinstance(v, RangeValue):
            for c in v.cells:
                if isinstance(c, bool):
                    out.append(c)
                elif isinstance(c, (int, float)):
                    out.append(c != 0)
        else:
            b = coerce_bool(v)
            if is_error(b):
                return None, b
            out.append(b)
    return out, None


def fn_and(vals):
    bools, err = _bool_values(vals)
    if err is not None:
        return err
    if not bools:
        return Error("#VALUE!")
    return all(bools)


def fn_or(vals):
    bools, err = _bool_values(vals)
    if err is not None:
        return err
    if not bools:
        return Error("#VALUE!")
    return any(bools)


def fn_not(vals):
    b = coerce_bool(vals[0])
    if is_error(b):
        return b
    return not b


def fn_round(vals):
    x = coerce_number(vals[0])
    if is_error(x):
        return x
    n = coerce_number(vals[1])
    if is_error(n):
        return n
    n = int(n)
    try:
        with localcontext() as ctx:
            ctx.prec = 50
            q = Decimal(1).scaleb(-n)
            d = Decimal(repr(float(x))).quantize(q, rounding=ROUND_HALF_UP)
        r = float(d)
    except Exception:
        return Error("#NUM!")
    if r == 0:
        r = 0.0
    return r


def fn_mod(vals):
    a = coerce_number(vals[0])
    if is_error(a):
        return a
    b = coerce_number(vals[1])
    if is_error(b):
        return b
    if b == 0:
        return Error("#DIV/0!")
    return a - b * math.floor(a / b)


def fn_power(vals):
    a = coerce_number(vals[0])
    if is_error(a):
        return a
    b = coerce_number(vals[1])
    if is_error(b):
        return b
    return op_power(a, b)


def fn_abs(vals):
    x = coerce_number(vals[0])
    if is_error(x):
        return x
    return abs(x)


def fn_int(vals):
    x = coerce_number(vals[0])
    if is_error(x):
        return x
    return math.floor(x)


def fn_sqrt(vals):
    x = coerce_number(vals[0])
    if is_error(x):
        return x
    if x < 0:
        return Error("#NUM!")
    return math.sqrt(x)


def fn_len(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    return len(s)


def _count_arg(v):
    n = coerce_number(v)
    if is_error(n):
        return None, n
    return int(n), None


def fn_left(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    n, err = _count_arg(vals[1])
    if err is not None:
        return err
    if n < 0:
        return Error("#VALUE!")
    return s[:n]


def fn_right(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    n, err = _count_arg(vals[1])
    if err is not None:
        return err
    if n < 0:
        return Error("#VALUE!")
    if n == 0:
        return ""
    return s[-n:]


def fn_mid(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    start, err = _count_arg(vals[1])
    if err is not None:
        return err
    length, err = _count_arg(vals[2])
    if err is not None:
        return err
    if start < 1 or length < 0:
        return Error("#VALUE!")
    return s[start - 1:start - 1 + length]


def fn_upper(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    return s.upper()


def fn_lower(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    return s.lower()


def fn_trim(vals):
    s = coerce_text(vals[0])
    if is_error(s):
        return s
    return re.sub(r" +", " ", s).strip(" ")


