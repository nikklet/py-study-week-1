#!/usr/bin/env python3
"""Reference spreadsheet formula engine.

Reads a JSON grid from stdin, evaluates every formula cell, and writes the
fully-computed grid as JSON to stdout.

Contract:  python reference_engine.py < input.json > out.json

This file is the authoritative definition of the engine's semantics. The hidden
golden outputs are generated by running compute() over each fixture input, so the
reference is correct by construction. See instruction.md for the human-readable
specification that mirrors the behavior implemented here.
"""

import sys
import io
import json
import math
import re
from decimal import Decimal, ROUND_HALF_UP, localcontext


# --------------------------------------------------------------------------- #
# Value model
# --------------------------------------------------------------------------- #
# Internal value types produced during evaluation:
#   * int / float          -- numbers (bool is NOT treated as a number here)
#   * bool                 -- TRUE / FALSE
#   * str                  -- text
#   * BLANK (sentinel)     -- an empty cell / empty reference target
#   * Error                -- an error value carrying an exact token string
#   * RangeValue           -- the value of a range expression (A1:B3)

ERROR_TOKENS = {
    "#DIV/0!", "#VALUE!", "#NAME?", "#REF!", "#NUM!", "#CIRCULAR!", "#ERROR!",
}


class Error:
    __slots__ = ("code",)

    def __init__(self, code):
        self.code = code

    def __repr__(self):
        return "Error(%r)" % self.code


class _Blank:
    __slots__ = ()

    def __repr__(self):
        return "BLANK"


BLANK = _Blank()


class RangeValue:
    """A materialized rectangular range: cells flattened row-major."""

    __slots__ = ("cells",)

    def __init__(self, cells):
        self.cells = cells  # list of internal scalar values, row-major


def is_error(v):
    return isinstance(v, Error)


# --------------------------------------------------------------------------- #
# Address helpers
# --------------------------------------------------------------------------- #
_ADDR_RE = re.compile(r"^\$?([A-Za-z]+)\$?([0-9]+)$")


def col_to_index(letters):
    """Bijective base-26: A->1, Z->26, AA->27, ..."""
    idx = 0
    for ch in letters.upper():
        idx = idx * 26 + (ord(ch) - ord("A") + 1)
    return idx


def index_to_col(idx):
    letters = ""
    while idx > 0:
        idx, rem = divmod(idx - 1, 26)
        letters = chr(ord("A") + rem) + letters
    return letters


def parse_addr(key):
    """Parse a cell key like 'A1' or '$B$2' -> (col_index, row_index)."""
    m = _ADDR_RE.match(key)
    if not m:
        raise ValueError("bad address: %r" % key)
    return col_to_index(m.group(1)), int(m.group(2))


def addr_str(col, row):
    return index_to_col(col) + str(row)


# --------------------------------------------------------------------------- #
# Tokenizer
# --------------------------------------------------------------------------- #
# Token kinds: ('num', value) ('str', value) ('ref', (col,row))
#              ('name', UPPER) ('op', symbol)
_TOKEN_RE = re.compile(
    r"""
      \s+                                   # whitespace (skipped)
    | (?P<num>  \d+\.\d+ | \d+\. | \.\d+ | \d+ )
    | (?P<str>  " (?: [^"] | "" )* " )
    | (?P<ref>  \$?[A-Za-z]+\$?[0-9]+ )
    | (?P<name> [A-Za-z_][A-Za-z0-9_.]* )
    | (?P<op>   <> | <= | >= | [-+*/^&=<>():,] )
    """,
    re.VERBOSE,
)


class ParseError(Exception):
    pass


def tokenize(text):
    tokens = []
    pos = 0
    n = len(text)
    while pos < n:
        m = _TOKEN_RE.match(text, pos)
        if not m or m.end() == pos:
            raise ParseError("bad character at %d: %r" % (pos, text[pos:pos + 8]))
        pos = m.end()
        if m.lastgroup is None:
            continue  # whitespace
        kind = m.lastgroup
        val = m.group()
        if kind == "num":
            tokens.append(("num", float(val) if "." in val else int(val)))
        elif kind == "str":
            inner = val[1:-1].replace('""', '"')
            tokens.append(("str", inner))
        elif kind == "ref":
            tokens.append(("ref", parse_addr(val)))
        elif kind == "name":
            tokens.append(("name", val.upper()))
        elif kind == "op":
            tokens.append(("op", val))
    return tokens


# --------------------------------------------------------------------------- #
# Parser (precedence climbing)
# --------------------------------------------------------------------------- #
# AST nodes (tuples):
#   ('num', v) ('str', v) ('bool', v)
#   ('ref', (col,row))
#   ('range', (c1,r1), (c2,r2))
#   ('unary', op, node)
#   ('binary', op, left, right)
#   ('func', NAME, [args])
#   ('nameerr', NAME)          -- bareword that is not TRUE/FALSE/function
#
# Binding powers (higher binds tighter). Binary operators are left-associative.
_BINDING = {
    "=": 1, "<>": 1, "<": 1, ">": 1, "<=": 1, ">=": 1,
    "&": 2,
    "+": 3, "-": 3,
    "*": 4, "/": 4,
    "^": 5,
}
_UNARY_BP = 6  # unary +/- bind tighter than ^  => -2^2 == (-2)^2 == 4


class Parser:
    def __init__(self, tokens):
        self.toks = tokens
        self.i = 0

    def peek(self):
        return self.toks[self.i] if self.i < len(self.toks) else None

    def next(self):
        t = self.toks[self.i]
        self.i += 1
        return t

    def expect_op(self, sym):
        t = self.peek()
        if t is None or t[0] != "op" or t[1] != sym:
            raise ParseError("expected %r" % sym)
        self.next()

    def parse(self):
        node = self.parse_expr(0)
        if self.i != len(self.toks):
            raise ParseError("trailing tokens")
        return node

    def parse_expr(self, min_bp):
        left = self.parse_prefix()
        while True:
            t = self.peek()
            if t is None or t[0] != "op":
                break
            op = t[1]
            bp = _BINDING.get(op)
            if bp is None or bp < min_bp:
                break
            self.next()
            right = self.parse_expr(bp + 1)  # +1 => left associative
            left = ("binary", op, left, right)
        return left

    def parse_prefix(self):
        t = self.peek()
        if t is not None and t[0] == "op" and t[1] in ("+", "-"):
            self.next()
            operand = self.parse_expr(_UNARY_BP)
            return ("unary", t[1], operand)
        return self.parse_atom()

    def parse_atom(self):
        t = self.peek()
        if t is None:
            raise ParseError("unexpected end")
        kind = t[0]
        if kind == "num":
            self.next()
            return ("num", t[1])
        if kind == "str":
            self.next()
            return ("str", t[1])
        if kind == "ref":
            self.next()
            start = t[1]
            nt = self.peek()
            if nt is not None and nt[0] == "op" and nt[1] == ":":
                self.next()
                nt2 = self.peek()
                if nt2 is None or nt2[0] != "ref":
                    raise ParseError("expected ref after ':'")
                self.next()
                return ("range", start, nt2[1])
            return ("ref", start)
        if kind == "name":
            self.next()
            name = t[1]
            nt = self.peek()
            if nt is not None and nt[0] == "op" and nt[1] == "(":
                self.next()
                args = self.parse_args()
                self.expect_op(")")
                return ("func", name, args)
            if name in ("TRUE", "FALSE"):
                return ("bool", name == "TRUE")
            return ("nameerr", name)
        if kind == "op" and t[1] == "(":
            self.next()
            node = self.parse_expr(0)
            self.expect_op(")")
            return node
        raise ParseError("unexpected token %r" % (t,))

    def parse_args(self):
        args = []
        if self.peek() is not None and self.peek() == ("op", ")"):
            return args
        args.append(self.parse_expr(0))
        while self.peek() == ("op", ","):
            self.next()
            args.append(self.parse_expr(0))
        return args


def parse_formula(text):
    return Parser(tokenize(text)).parse()


# --------------------------------------------------------------------------- #
# Coercions
# --------------------------------------------------------------------------- #
def format_number(x):
    """Format a number for text contexts: integral -> no decimal point."""
    if isinstance(x, bool):
        return "TRUE" if x else "FALSE"
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        if x != x or x in (float("inf"), float("-inf")):
            return str(x)
        if x.is_integer():
            return str(int(x))
        return repr(x)
    return str(x)


def coerce_number(v):
    if is_error(v):
        return v
    if isinstance(v, bool):
        return 1 if v else 0
    if isinstance(v, (int, float)):
        return v
    if v is BLANK:
        return 0
    return Error("#VALUE!")  # text or range


def coerce_text(v):
    if is_error(v):
        return v
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if v is BLANK:
        return ""
    if isinstance(v, str):
        return v
    if isinstance(v, (int, float)):
        return format_number(v)
    return Error("#VALUE!")  # range


def coerce_bool(v):
    """Boolean scalar context (IF condition, AND/OR/NOT scalar args)."""
    if is_error(v):
        return v
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return v != 0
    if v is BLANK:
        return False
    return Error("#VALUE!")  # text or range


def type_class(v):
    if isinstance(v, bool):
        return "bool"
    if isinstance(v, (int, float)):
        return "num"
    if isinstance(v, str):
        return "text"
    if v is BLANK:
        return "blank"
    return "range"


# --------------------------------------------------------------------------- #
# Operators
# --------------------------------------------------------------------------- #
def op_arith(op, a, b):
    a = coerce_number(a)
    if is_error(a):
        return a
    b = coerce_number(b)
    if is_error(b):
        return b
    if op == "+":
        return a + b
    if op == "-":
        return a - b
    if op == "*":
        return a * b
    if op == "/":
        if b == 0:
            return Error("#DIV/0!")
        return a / b
    if op == "^":
        return op_power(a, b)
    raise ParseError("bad op")


def op_power(a, b):
    if a < 0 and not float(b).is_integer():
        return Error("#NUM!")
    try:
        r = a ** b
    except (OverflowError, ValueError, ZeroDivisionError):
        return Error("#NUM!")
    if isinstance(r, complex):
        return Error("#NUM!")
    if isinstance(r, float) and (r != r or r in (float("inf"), float("-inf"))):
        return Error("#NUM!")
    return r


def op_unary(op, v):
    v = coerce_number(v)
    if is_error(v):
        return v
    return -v if op == "-" else +v


def op_concat(a, b):
    a = coerce_text(a)
    if is_error(a):
        return a
    b = coerce_text(b)
    if is_error(b):
        return b
    return a + b


def values_equal(a, b):
    ta, tb = type_class(a), type_class(b)
    if ta == "blank" and tb == "blank":
        return True
    if ta == "blank":
        if tb == "num":
            return 0 == b
        if tb == "text":
            return b == ""
        return False  # blank vs bool
    if tb == "blank":
        return values_equal(b, a)
    if ta != tb:
        return False
    if ta == "text":
        return a.upper() == b.upper()
    return a == b  # num or bool


def op_compare(op, a, b):
    if is_error(a):
        return a
    if is_error(b):
        return b
    if isinstance(a, RangeValue) or isinstance(b, RangeValue):
        return Error("#VALUE!")
    if op == "=":
        return values_equal(a, b)
    if op == "<>":
        return not values_equal(a, b)
    # ordering: <, >, <=, >=
    # Type classes for ordering are number, text, and boolean. A blank operand
    # adopts the OTHER operand's type (number -> 0, text -> ""). Any remaining
    # cross-class ordering (including boolean vs number/text) is #VALUE!.
    ta, tb = type_class(a), type_class(b)
    if ta == "blank" and tb == "blank":
        a, b, ta, tb = 0, 0, "num", "num"
    elif ta == "blank":
        if tb == "num":
            a, ta = 0, "num"
        elif tb == "text":
            a, ta = "", "text"
        else:  # bool
            return Error("#VALUE!")
    elif tb == "blank":
        if ta == "num":
            b, tb = 0, "num"
        elif ta == "text":
            b, tb = "", "text"
        else:  # bool
            return Error("#VALUE!")
    if ta != tb:
        return Error("#VALUE!")
    if ta == "bool":
        a, b = (1 if a else 0), (1 if b else 0)
    elif ta == "text":
        a, b = a.upper(), b.upper()
    if op == "<":
        return a < b
    if op == ">":
        return a > b
    if op == "<=":
        return a <= b
    if op == ">=":
        return a >= b
    raise ParseError("bad op")


